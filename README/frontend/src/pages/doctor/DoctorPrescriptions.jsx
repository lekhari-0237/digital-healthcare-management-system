import React, { useEffect, useState } from 'react';
import { prescriptionService } from '../../services/prescriptionService';
import PrescriptionModal from '../../components/patient/PrescriptionModal';
import Loader from '../../components/common/Loader';
import EmptyState from '../../components/common/EmptyState';
import { FileText, Eye } from 'lucide-react';

export default function DoctorPrescriptions() {
  const [prescriptions, setPrescriptions] = useState([]);
  const [loading, setLoading] = useState(true);
  const [selectedPrescription, setSelectedPrescription] = useState(null);

  useEffect(() => {
    fetchPrescriptions();
  }, []);

  const fetchPrescriptions = async () => {
    setLoading(true);
    try {
      const data = await prescriptionService.getMyPrescriptions();
      setPrescriptions(data);
    } catch (err) {
      console.error('Error fetching prescriptions:', err);
    } finally {
      setLoading(false);
    }
  };

  if (loading) return <Loader label="Loading issued prescriptions..." />;

  return (
    <div className="space-y-6">
      <div>
        <h1 className="text-2xl font-extrabold text-slate-900">Issued Digital Prescriptions</h1>
        <p className="text-xs text-slate-500 mt-1">Archived digital prescriptions generated by you for patient consultations.</p>
      </div>

      {prescriptions.length === 0 ? (
        <EmptyState
          title="No Prescriptions Generated"
          description="Prescriptions will be listed here after you complete patient consultations."
        />
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
          {prescriptions.map((rx) => (
            <div key={rx._id} className="bg-white rounded-3xl border border-slate-100 p-6 shadow-sm flex flex-col justify-between space-y-4">
              <div>
                <h3 className="font-extrabold text-slate-900 text-sm">Patient: {rx.patientId?.name || 'Patient'}</h3>
                <span className="text-[10px] font-bold text-slate-400 block mt-0.5">
                  Date: {new Date(rx.createdAt).toLocaleDateString()}
                </span>

                <div className="bg-slate-50 p-3 rounded-2xl text-xs space-y-1 mt-3">
                  <p className="font-bold text-sky-900">Diagnosis: {rx.diagnosis}</p>
                  <p className="text-slate-600">{rx.medicines?.length || 0} Medicines prescribed</p>
                </div>
              </div>

              <button
                onClick={() => setSelectedPrescription(rx)}
                className="w-full py-2.5 bg-sky-600 hover:bg-sky-700 text-white font-bold text-xs rounded-xl shadow-md transition flex items-center justify-center gap-1.5"
              >
                <Eye className="h-4 w-4" /> View Prescription PDF
              </button>
            </div>
          ))}
        </div>
      )}

      {/* Prescription PDF Modal */}
      <PrescriptionModal
        isOpen={!!selectedPrescription}
        onClose={() => setSelectedPrescription(null)}
        prescription={selectedPrescription}
      />
    </div>
  );
}
